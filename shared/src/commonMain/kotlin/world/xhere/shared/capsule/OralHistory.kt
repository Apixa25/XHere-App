package world.xhere.shared.capsule

/**
 * Prompts for an oral-history capsule. They are not tied to one town.
 * The person answers in their own words. The questions are suggestions.
 */
object OralHistory {
    val questions: List<String> = listOf(
        "What did this place look like when you were young?",
        "Who did you come here with, and what did you do?",
        "What should someone who arrives later know about the people who were here?",
        "Was there a sound, a smell, or a season you still remember from this spot?",
        "What changed here that a map would not show?",
    )
}
